"""Native monochrome glyphs: FreeType/Pillow, one source pixel per panel pixel.

Requires Pillow. Never resize, dilate, repair or dither a rasterized glyph.
Run from any directory; output is reproducible for the same Pillow/FreeType.
"""
from pathlib import Path
from PIL import ImageFont
from hashlib import sha256

root=Path(__file__).resolve().parents[1]
font_path=root/'fonts/RobotoCondensed-Bold.ttf'
output=root/'components/goats_st7306/native_glyphs.h'
sizes=(13,16,20,24,28,32,36,40,44,48,52,56,60,64,72,78,82,95)
parts=['#pragma once','#include <cstdint>','namespace esphome::goats_st7306::native {',
       '// Generated by fonts/generate_native.py; monochrome at native pixel sizes.',
       '// Font SHA-256: '+sha256(font_path.read_bytes()).hexdigest(),
       'struct Glyph {uint32_t offset; int16_t left,top; uint16_t width,height,advance;};',
       'struct Face {int size; const Glyph *glyphs; const uint8_t *bits; int last;};']
for size in sizes:
    font=ImageFont.truetype(str(font_path),size,layout_engine=ImageFont.Layout.BASIC)
    last=255 if size<=28 else 126
    glyphs=[];bits=[]
    for code in range(32,last+1):
        mask, (left,top)=font.getmask2(chr(code),mode='1',anchor='ls')
        width,height=mask.size
        advance=round(font.getlength(chr(code)))
        glyphs.append((len(bits),left,top,width,height,advance))
        values=list(mask)
        for at in range(0,len(values),8):
            byte=0
            for bit,value in enumerate(values[at:at+8]):
                if value:byte|=0x80>>bit
            bits.append(byte)
    parts.append(f'inline constexpr uint8_t bits_{size}[] = {{')
    for at in range(0,len(bits),32):parts.append(','.join(str(v) for v in bits[at:at+32])+',')
    parts.append('};')
    parts.append(f'inline constexpr Glyph glyphs_{size}[] = {{')
    parts.extend('{'+','.join(str(v) for v in glyph)+'},' for glyph in glyphs)
    parts.append('};')
parts.append('inline constexpr Face faces[] = {')
for size in reversed(sizes):parts.append(f'{{{size},glyphs_{size},bits_{size},{255 if size<=28 else 126}}},')
parts.extend(['};','}  // namespace esphome::goats_st7306::native'])
output.write_text('\n'.join(parts)+'\n')
print(output.name, output.stat().st_size,'bytes; native 1 bpp, no scaling')
